/**
 * Prisma Database Client Stub / Loader
 * 
 * IMPORTANT:
 * - Member 3 owns schema.prisma and migrations.
 * - This module provides safe initialization. If Member 3 hasn't run
 *   'prisma generate' yet, it fails gracefully without crashing the server.
 * - Once Member 3 finalizes schema.prisma and runs 'npx prisma generate',
 *   the real PrismaClient instance is automatically active.
 */

let prisma = null;

try {
  const { PrismaClient } = await import('@prisma/client');
  prisma = new PrismaClient({
    log: process.env.NODE_ENV === 'development' ? ['query', 'error', 'warn'] : ['error'],
  });
} catch (error) {
  // Graceful fallback when Prisma schema / client is not yet generated by Member 3
  console.info(
    '[Database] Note: Prisma client is not yet generated by Member 3. Database operations will activate after Member 3 runs "prisma generate".'
  );
  prisma = new Proxy(
    {},
    {
      get: (_target, prop) => {
        return () => {
          throw new Error(
            `Database model '${String(prop)}' is not available yet. Member 3 is finalizing schema.prisma.`
          );
        };
      },
    }
  );
}

export default prisma;
